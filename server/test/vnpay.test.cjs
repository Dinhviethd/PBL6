const { test } = require("node:test");
const assert = require("node:assert/strict");
const { createHmac } = require("node:crypto");
const {
  vnpayProvider,
  vnpDate,
  canonical,
} = require("../dist/modules/payment/vnpay");
const { paymentProviderFromEnv } = require("../dist/modules/payment/public");
const { smtpOptions } = require("../dist/platform/smtp");
const config = {
  tmnCode: "TEST1234",
  hashSecret: "test-vnpay-secret-32-characters!!",
  publicApiUrl: "https://example.ngrok-free.app",
};
const hash = (data) =>
  createHmac("sha512", config.hashSecret).update(data).digest("hex");
const input = {
  orderId: "order",
  amount: "100000",
  expiresAt: new Date(Date.now() + 900000),
  reference: "123abc",
  ip: "127.0.0.1",
};
const ipn = (overrides = {}) => {
  const f = {
    vnp_TmnCode: config.tmnCode,
    vnp_TxnRef: input.reference,
    vnp_Amount: "10000000",
    vnp_ResponseCode: "00",
    vnp_TransactionStatus: "00",
    vnp_TransactionNo: "12345",
    ...overrides,
  };
  return { ...f, vnp_SecureHash: hash(canonical(f)) };
};
test("VNPay sandbox URL uses VND integer scaling, UTC+7 and sorted form encoding", () => {
  assert.equal(vnpDate(new Date("2026-10-13T20:00:00Z")), "20261014030000");
  const intent = vnpayProvider(config).createIntent(input),
    url = new URL(intent.checkoutUrl);
  assert.equal(url.origin, "https://sandbox.vnpayment.vn");
  assert.equal(url.searchParams.get("vnp_Amount"), "10000000");
  assert.equal(
    url.searchParams.get("vnp_ReturnUrl"),
    `${config.publicApiUrl}/api/payments/vnpay/return`,
  );
  // Independent encoding vector (not generated by canonical).
  assert.equal(
    canonical({ vnp_Z: "A B+C/", vnp_A: "1" }),
    "vnp_A=1&vnp_Z=A+B%2BC%2F",
  );
  const signature = url.searchParams.get("vnp_SecureHash");
  url.searchParams.delete("vnp_SecureHash");
  assert.equal(signature, hash(url.searchParams.toString()));
  assert.equal(intent.reconcileUntil - input.expiresAt, 300000);
  assert.throws(
    () =>
      vnpayProvider(config).createIntent({ ...input, amount: "10000000000" }),
    /giới hạn/,
  );
});
test("IPN rejects tampering, wrong merchant, duplicate parameters and missing transaction", () => {
  const p = vnpayProvider(config);
  assert.equal(p.verifyIpn(ipn()).status, "SUCCEEDED");
  assert.throws(() => p.verifyIpn({ ...ipn(), vnp_Amount: "1" }), /Chữ ký/);
  assert.throws(
    () => p.verifyIpn(ipn({ vnp_TmnCode: "OTHER123" })),
    /Merchant/,
  );
  assert.throws(
    () => p.verifyIpn({ ...ipn(), vnp_Amount: ["100", "200"] }),
    /Dữ liệu/,
  );
  assert.throws(
    () => p.verifyIpn(ipn({ vnp_TransactionNo: "0" })),
    /mã giao dịch/,
  );
  assert.equal(
    p.verifyIpn(
      ipn({
        vnp_ResponseCode: "24",
        vnp_TransactionStatus: "02",
        vnp_TransactionNo: "0",
      }),
    ).status,
    "FAILED",
  );
  assert.equal(
    p.verifyIpn(ipn({ vnp_TransactionStatus: "01" })).status,
    "UNKNOWN",
  );
});
test("querydr verifies response signature and distinguishes query errors from payment failure", async () => {
  const keys = [
    "ResponseId",
    "Command",
    "ResponseCode",
    "Message",
    "TmnCode",
    "TxnRef",
    "Amount",
    "BankCode",
    "PayDate",
    "TransactionNo",
    "TransactionType",
    "TransactionStatus",
    "OrderInfo",
    "PromotionCode",
    "PromotionAmount",
  ];
  let overrides = {},
    tamper = false;
  const p = vnpayProvider(config, async (url, options) => {
    assert.equal(
      url,
      "https://sandbox.vnpayment.vn/merchant_webapi/api/transaction",
    );
    const request = JSON.parse(options.body);
    assert.equal(request.vnp_TransactionDate, originalDate);
    assert.equal(
      request.vnp_SecureHash,
      hash(
        [
          request.vnp_RequestId,
          "2.1.0",
          "querydr",
          config.tmnCode,
          input.reference,
          originalDate,
          request.vnp_CreateDate,
          "127.0.0.1",
          request.vnp_OrderInfo,
        ].join("|"),
      ),
    );
    const result = {
      ...ipn(),
      vnp_ResponseId: "response1",
      vnp_Command: "querydr",
      vnp_TransactionType: "01",
      vnp_Message: "Success",
      ...overrides,
    };
    result.vnp_SecureHash = hash(
      keys.map((k) => result[`vnp_${k}`] ?? "").join("|"),
    );
    if (tamper) result.vnp_Amount = "1";
    return { ok: true, json: async () => result };
  });
  const checkout_url = p.createIntent(input).checkoutUrl,
    originalDate = new URL(checkout_url).searchParams.get("vnp_CreateDate");
  const payment = { merchant_reference: input.reference, checkout_url };
  assert.equal((await p.reconcile(payment)).status, "SUCCEEDED");
  overrides = { vnp_Amount: 10000000, vnp_TransactionNo: 12345 };
  assert.equal((await p.reconcile(payment)).status, "SUCCEEDED");
  overrides = { vnp_ResponseCode: "91" };
  assert.equal(await p.reconcile(payment), null);
  overrides = {};
  tamper = true;
  await assert.rejects(p.reconcile(payment), /Chữ ký/);
  const broken = vnpayProvider(config, async () => {
    throw new DOMException("timeout", "TimeoutError");
  });
  await assert.rejects(broken.reconcile(payment), /timeout/);
});
test("configuration is fail-closed; Gmail enforces authenticated STARTTLS and sender", () => {
  assert.throws(
    () => paymentProviderFromEnv({ PAYMENT_MODE: "vnpay_sandbox" }),
    /VNPAY/,
  );
  assert.throws(
    () =>
      paymentProviderFromEnv({
        PAYMENT_MODE: "vnpay_sandbox",
        NODE_ENV: "production",
      }),
    /production/,
  );
  assert.throws(
    () => vnpayProvider({ ...config, publicApiUrl: "http://localhost:8000" }),
    /HTTPS/,
  );
  assert.throws(() => smtpOptions({}), /SMTP_HOST/);
  const env = {
    SMTP_HOST: "smtp.gmail.com",
    SMTP_FROM: "EventHub <test@gmail.com>",
    SMTP_USER: "test@gmail.com",
    SMTP_PASS: "app-password",
    SMTP_PORT: "587",
    SMTP_SECURE: "false",
  };
  const options = smtpOptions(env);
  assert.equal(options.requireTLS, true);
  assert.equal(options.secure, false);
  assert.throws(
    () => smtpOptions({ ...env, SMTP_FROM: "other@gmail.com" }),
    /cùng địa chỉ/,
  );
  assert.throws(() => smtpOptions({ ...env, SMTP_PASS: "" }), /SMTP_PASS/);
  assert.throws(
    () => smtpOptions({ ...env, SMTP_SECURE: "true" }),
    /SMTP_PORT/,
  );
});
